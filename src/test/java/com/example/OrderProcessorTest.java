package com.example;

import java.io.File;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

public class OrderProcessorTest {
    private OrderProcessor processor;

    @BeforeEach
    void setUp() {
        processor = new OrderProcessor();
    }

    @Test
    void testProcessOrderSuccess() {
        double total = processor.processOrder("ORD-101", 150.0, 3);
        assertEquals(450.0, total, 0.001);

        File logFile = new File("logs/application.log");
        assertTrue(logFile.exists(), "Log file should be generated by FileAppender");
    }

    @Test
    void testProcessOrderInvalidPrice() {
        assertThrows(IllegalArgumentException.class, () -> processor.processOrder("ORD-102", -50.0, 2));
    }

    @Test
    void testProcessOrderEmptyId() {
        assertThrows(IllegalArgumentException.class, () -> processor.processOrder("", 100.0, 1));
    }
}
